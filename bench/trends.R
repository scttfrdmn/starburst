#!/usr/bin/env Rscript
# bench/trends.R — aggregate every dated result in bench/results/ into trends.
#
# Reads both result formats:
#   <workload>-<date>.rds   from benchmark.R   (list with $runs, end-to-end phases)
#   components-<date>.rds   from components.R  (data.frame, one row per metric)
# and writes:
#   bench/results/trends.md    every metric × date, in seconds (the table view)
#   bench/results/trends.png   small multiples of the headline metrics over time
#
# Free and local: no AWS, no opt-in. Base R only (grDevices/graphics).
#
# Usage: Rscript bench/trends.R [results-dir]

args <- commandArgs(trailingOnly = TRUE)
dir <- if (length(args)) args[1] else file.path("bench", "results")
files <- list.files(dir, pattern = "\\.rds$", full.names = TRUE)
if (!length(files)) stop("no .rds results in ", dir)

# ---- Normalize to one long table: date, metric, seconds ----------------------
rows <- list()
add <- function(date, metric, seconds) {
  rows[[length(rows) + 1]] <<- data.frame(date = as.Date(date), metric = metric,
                                          seconds = seconds, stringsAsFactors = FALSE)
}
for (f in files) {
  x <- readRDS(f)
  if (is.data.frame(x)) {
    # components.R. Component prefix keeps e.g. serialize/s3 metrics distinct.
    for (i in seq_len(nrow(x))) {
      add(x$date[i], paste0(x$component[i], ": ", x$metric[i]), x$seconds[i])
    }
  } else if (is.list(x) && !is.null(x$runs)) {
    # benchmark.R. One metric per workload × phase × cold/warm.
    for (r in x$runs) {
      mode <- if (isTRUE(r$warm)) "warm" else "cold"
      for (ph in c("startup_secs", "compute_collect_secs", "total_secs")) {
        add(x$date, sprintf("e2e: %s %s (%s)", r$name, sub("_secs$", "", ph), mode), r[[ph]])
      }
    }
  }
}
d <- do.call(rbind, rows)
# Several runs on one date (e.g. re-runs) collapse to their median.
d <- aggregate(seconds ~ date + metric, data = d, FUN = median)
d <- d[order(d$metric, d$date), ]

# ---- Table view --------------------------------------------------------------
dates <- sort(unique(d$date))
metrics <- sort(unique(d$metric))
cell <- function(m, dt) {
  v <- d$seconds[d$metric == m & d$date == dt]
  if (length(v)) sprintf("%.2f", v) else ""
}
md <- c(
  "# staRburst benchmark trends",
  "",
  "> Generated by `bench/trends.R` from every result in `bench/results/`. Seconds;",
  "> medians where a date has several runs. See `trends.png` for the headline charts.",
  "",
  paste0("| Metric | ", paste(format(dates), collapse = " | "), " |"),
  paste0("|---|", paste(rep("---", length(dates)), collapse = "|"), "|"),
  vapply(metrics, function(m) paste0("| ", m, " | ",
         paste(vapply(dates, function(dt) cell(m, dt), ""), collapse = " | "), " |"), "")
)
writeLines(md, file.path(dir, "trends.md"))

# ---- Headline chart: small multiples, one metric per panel -------------------
# One series per panel, each on its own y-axis (never two scales on one panel).
# The panel title names the series, so no legend is needed.
headline <- c(
  grep("^e2e: .* total \\(", metrics, value = TRUE),
  grep("^serialize: qs_(save|read) 10 MB$", metrics, value = TRUE),
  grep("^s3: (put|get) 10 MB$", metrics, value = TRUE),
  grep("^image: ", metrics, value = TRUE),
  grep("^ci: ", metrics, value = TRUE)
)
if (length(headline)) {
  ink <- "#0b0b0b"; muted <- "#898781"; grid_col <- "#e1e0d9"
  surface <- "#fcfcfb"; series <- "#2a78d6"
  ncol <- min(4L, length(headline))
  nrow <- ceiling(length(headline) / ncol)
  png(file.path(dir, "trends.png"), width = 420 * ncol, height = 300 * nrow, res = 120,
      bg = surface)
  op <- par(mfrow = c(nrow, ncol), mar = c(3, 3.2, 2.6, 1), mgp = c(2, 0.5, 0),
            col.axis = muted, fg = muted, bg = surface, las = 1, tcl = -0.2)
  xr <- range(dates)
  if (diff(xr) == 0) xr <- xr + c(-15, 15)
  for (m in headline) {
    s <- d[d$metric == m, ]
    # Pick a unit per panel so tick labels stay short; the title carries the unit.
    mx <- max(s$seconds)
    u <- if (mx < 1) list(k = 1000, lab = "ms") else if (mx >= 600) list(k = 1 / 60, lab = "min") else list(k = 1, lab = "s")
    y <- s$seconds * u$k
    yr <- c(0, max(y) * 1.15)
    plot(s$date, y, type = "n", xlim = xr, ylim = yr, axes = FALSE, xlab = "", ylab = "")
    abline(h = pretty(yr), col = grid_col, lwd = 1)
    axis(2, at = pretty(yr), lwd = 0, lwd.ticks = 0)
    axis.Date(1, at = pretty(xr, n = 4), format = "%Y-%m", lwd = 0, lwd.ticks = 0)
    lines(s$date, y, col = series, lwd = 2)
    points(s$date, y, pch = 21, bg = series, col = surface, cex = 1.4, lwd = 1.5)
    # Label only the most recent value (selective direct label, in ink, not series color).
    n <- length(y)
    text(s$date[n], y[n], sprintf("%s %s", format(signif(y[n], 3)), u$lab), pos = 3,
         col = ink, cex = 0.8, xpd = NA)
    title(main = sprintf("%s (%s)", sub("^(e2e|ci|serialize|image): ", "", sub("^s3: ", "S3 ", m)), u$lab), col.main = ink,
          font.main = 1, cex.main = 0.85, adj = 0)
  }
  par(op)
  invisible(dev.off())
}

message(sprintf("Wrote %s (%d metrics × %d dates) and trends.png (%d panels)",
                file.path(dir, "trends.md"), length(metrics), length(dates), length(headline)))
